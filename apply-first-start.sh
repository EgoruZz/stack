#!/bin/bash
# Applies the filled-in first-start form (first-start.txt).
# Run:  bash $STACK_DIR/apply-first-start.sh [path-to-form]
# By default looks for $STACK_DIR/first-start.txt (a copy of the template with data).

set -uo pipefail

STACK_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FORM="${1:-$STACK_DIR/first-start.txt}"
SECRETS="$HOME/.stack-secrets.sh"

[ -f "$FORM" ] || { echo "Form not found: $FORM"; echo "Copy the template: cp $STACK_DIR/first-start.template.txt $STACK_DIR/first-start.txt and fill it in."; exit 1; }

# Parse the form line by line (not source!): spaces in values and
# missing quotes must not break parsing; strip trailing # comments.
FORM_VARS=""
while IFS= read -r line || [ -n "$line" ]; do
    line="${line%%#*}"            # strip comment
    line="${line%"${line##*[![:space:]]}"}"   # trim right
    case "$line" in
        [A-Z_]*=*) ;;
        *) continue ;;
    esac
    key="${line%%=*}"; val="${line#*=}"
    val="${val%\"}"; val="${val#\"}"      # strip optional quotes
    val="${val%\'}"; val="${val#\'}"
    eval "$key=\$val"
    export "$key"
done < "$FORM"

# Fields not set in the form -> empty (set -u safe)
for v in PROXY_HOST PROXY_USER PROXY_PASS PROXY_EXPIRES GIT_NAME GIT_EMAIL WOLFRAM_ID WOLFRAM_PASS AGENT_SUDO; do
    eval "test -n \"\${$v+x}\" || $v=''"
done
# The proxy is OPTIONAL: either all fields of the block are filled, or none
P_EMPTY=0; P_FULL=0
for v in PROXY_HOST PROXY_USER PROXY_PASS; do
    eval "val=\${$v}"
    [ -z "$val" ] && P_EMPTY=$((P_EMPTY+1)) || P_FULL=$((P_FULL+1))
done
if [ "$P_EMPTY" -gt 0 ] && [ "$P_FULL" -gt 0 ]; then
    echo "❌ Proxy block half-filled — fill in all PROXY_* fields or leave them empty (no proxy)"
    exit 1
fi

# ~/.stack-secrets.sh — only if the proxy is configured
if [ "$P_FULL" = "0" ]; then
    rm -f "$SECRETS"
    echo "ℹ️ Proxy not configured (optional) — the stack works direct"
else
cat > "$SECRETS" << EOF
# Generated by apply-first-start.sh from first-start.txt $(date +%F)
PROXY_HOST="$PROXY_HOST"
PROXY_USER="$PROXY_USER"
PROXY_PASS="$PROXY_PASS"
PROXY_EXPIRES="$PROXY_EXPIRES"
EOF
chmod 600 "$SECRETS"
echo "✅ $SECRETS written (600)"
fi

# git identity
if [ -n "${GIT_NAME:-}" ] && [ -n "${GIT_EMAIL:-}" ]; then
    git config --global user.name "$GIT_NAME"
    git config --global user.email "$GIT_EMAIL"
    echo "✅ git identity: $GIT_NAME <$GIT_EMAIL>"
else
    echo "⚠️ git identity not filled in — commits will use the system name"
fi

# Wolfram ID — saved to a protected file for future activation
if [ -n "${WOLFRAM_ID:-}" ] && [ -n "${WOLFRAM_PASS:-}" ]; then
    cat > "$HOME/.stack-wolfram.conf" << EOF
WOLFRAM_ID="$WOLFRAM_ID"
WOLFRAM_PASS="$WOLFRAM_PASS"
EOF
    chmod 600 "$HOME/.stack-wolfram.conf"
    echo "✅ Wolfram ID saved (~/.stack-wolfram.conf, 600) — activation: wolframscript -activate"
else
    echo "ℹ️ Wolfram ID not filled in (optional)"
fi

echo ""
echo "Done. Check: bash $STACK_DIR/proxy.sh test && bash $STACK_DIR/check-all.sh"

# Passwordless sudo for the agent (optional)
SUDOERS="/etc/sudoers.d/stack-agent"
SUDOERS_TPL="$HOME/.stack-sudoers.tpl"
if [ "$AGENT_SUDO" = "full" ]; then
    echo "$USER ALL=(ALL) NOPASSWD: ALL" > "$SUDOERS_TPL"
    echo ""
    echo "⚠️  AGENT_SUDO=full selected: the agent and all processes running as"
    echo "    your user will get root without a password. If this is a deliberate"
    echo "    decision, run:"
    echo "      sudo install -m 440 \"$SUDOERS_TPL\" $SUDOERS"
    echo "    (sudo will ask for the password once — afterwards the agent has passwordless sudo)"
    echo "    Undo: sudo rm -f $SUDOERS && rm -f $SUDOERS_TPL"
elif [ -f "$SUDOERS" ]; then
    echo ""
    echo "ℹ️  Sudoers file $SUDOERS exists, but AGENT_SUDO != full."
    echo "    Remove the permanent NOPASSWD: sudo rm -f $SUDOERS"
fi

echo "The form $FORM stays in place: if the data changes (different proxy,"
echo "account, subscription term) — just edit it and run again."
